  // Helper Methods
  static List<DuaItem> get allDuas {
    final List<DuaItem> list = [];
    for (final duas in duasMap.values) {
      list.addAll(duas);
    }
    return list;
  }

  static DuaItem? getDuaById(String id) {
    for (final duas in duasMap.values) {
      for (final dua in duas) {
        if (dua.id == id) return dua;
      }
    }
    return null;
  }

  static List<DuaItem> searchDuas(String query) {
    if (query.trim().isEmpty) return [];
    final q = query.toLowerCase().trim();
    return allDuas.where((d) {
      return d.title.toLowerCase().contains(q) ||
          d.translation.toLowerCase().contains(q) ||
          d.transliteration.toLowerCase().contains(q) ||
          d.reference.toLowerCase().contains(q) ||
          d.arabic.contains(q) ||
          d.tags.any((tag) => tag.toLowerCase().contains(q));
    }).toList();
  }

  static List<DuaItem> getFavoriteDuas(List<String> favoriteIds) {
    if (favoriteIds.isEmpty) return [];
    return allDuas.where((d) => favoriteIds.contains(d.id)).toList();
  }
